import {test,expect} from '@playwright/test'
test('XL default arena and preserved classic invitations use separate physical sizes',async({page},info)=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('./?challenge=sd2-d20261028')
 await expect(page.getByTestId('sd-start')).toBeEnabled({timeout:60_000})
 await expect(page.getByTestId('showdown-game')).toHaveAttribute('data-arena-width','164')
 await expect(page.getByTestId('showdown-game')).toHaveAttribute('data-bots','16')
 await page.screenshot({path:info.outputPath('xl-arena-menu.png'),animations:'disabled'})
 await page.getByTestId('sd-start').click()
 await expect(page.getByTestId('sd-touch-forward')).toBeVisible({timeout:15_000})
 await page.keyboard.down('w');await page.waitForTimeout(10000);await page.keyboard.up('w')
 await expect(page.getByTestId('sd-score')).not.toHaveText('0')
 await page.getByTestId('sd-pause').click()
 await page.screenshot({path:info.outputPath('xl-arena-driving.png'),animations:'disabled'})
 await page.goto('./?challenge=sd1-d20261028&score=200')
 await expect(page.getByTestId('sd-start')).toBeEnabled({timeout:30_000})
 await expect(page.getByTestId('showdown-game')).toHaveAttribute('data-arena-width','82')
 await expect(page.getByTestId('showdown-game')).toHaveAttribute('data-bots','10')
 await expect(page.getByTestId('sd-invite')).toContainText('200')
 expect(errors).toEqual([])
})
test('four outer districts render and drive well outside the original map',async({page},info)=>{
 const errors=[],failed=[];page.on('pageerror',e=>errors.push(e.message));page.on('requestfailed',r=>{if(!r.url().includes('fonts.'))failed.push(r.url())})
 await page.goto('./?view=world')
 await expect(page.getByTestId('start-explore')).toBeEnabled({timeout:60_000})
 await page.getByTestId('start-explore').click()
 for(const id of ['evergreen','aurora','sunset','redrock']){
   await page.getByTestId('open-map').click()
   await expect(page.locator('[data-testid^="travel-"]')).toHaveCount(13)
   await page.getByTestId(`travel-${id}`).click()
   await expect(page.getByTestId('touch-forward')).toBeVisible()
   const read=()=>page.getByTestId('world-hud').getAttribute('data-world-x')
   await expect.poll(async()=>Math.abs(Number(await read()))).toBeGreaterThan(200)
   await page.waitForTimeout(1400)
   await page.screenshot({path:info.outputPath(`frontier-${id}-arrival.png`),animations:'disabled'})
   const initial=Number(await page.getByTestId('world-hud').getAttribute('data-world-z'))
   await page.keyboard.down('w');await page.waitForTimeout(1900);await page.keyboard.up('w')
   await expect.poll(async()=>Math.abs(Number(await page.getByTestId('world-hud').getAttribute('data-world-z'))-initial)).toBeGreaterThan(4)
   await page.screenshot({path:info.outputPath(`frontier-${id}.png`),animations:'disabled'})
 }
 await page.getByTestId('open-map').click()
 await page.screenshot({path:info.outputPath('expanded-world-map.png'),animations:'disabled'})
 await page.getByTestId('travel-village').click()
 await expect.poll(async()=>Math.abs(Number(await page.getByTestId('world-hud').getAttribute('data-world-x'))+63)).toBeLessThan(3)
 await page.getByTestId('switch-mode').click();await expect(page.locator('.countdown-overlay')).toBeVisible()
 expect(errors).toEqual([]);expect(failed).toEqual([])
})
