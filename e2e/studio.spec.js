import {test,expect} from '@playwright/test'
async function lobby(page){await page.goto('./?view=battle');await expect(page.getByTestId('battle-start')).toBeEnabled({timeout:60000})}
test('garage opens, upgrades persist and track creator launches custom elevated racetrack',async({page},info)=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await lobby(page)
 await page.getByTestId('open-garage').click()
 await expect(page.getByRole('dialog',{name:'ANIK kart garage'})).toBeVisible()
 await expect(page.getByTestId('garage-credits')).toContainText('0')
 await expect(page.getByTestId('garage-upgrade-engine')).toBeDisabled()
 await page.getByRole('button',{name:'Close kart garage'}).click()
 await page.getByTestId('open-editor').click()
 await expect(page.getByTestId('studio-editor-map')).toBeVisible()
 await page.getByTestId('studio-track-name').fill('PLAYWRIGHT SKY TRACK')
 await page.getByTestId('studio-height').focus()
 await page.keyboard.press('ArrowRight')
 await page.getByTestId('studio-test-track').click()
 await expect(page.getByTestId('battle-game')).toHaveAttribute('data-track','custom')
 await expect(page.getByTestId('battle-track-custom')).toContainText('PLAYWRIGHT SKY TRACK')
 await page.screenshot({path:info.outputPath('studio-custom-track-lobby.png'),animations:'disabled'})
 await page.getByTestId('battle-start').click()
 await expect(page.getByTestId('battle-forward')).toBeVisible({timeout:15000})
 await page.keyboard.down('w');await page.waitForTimeout(1800);await page.keyboard.up('w')
 await expect(page.getByTestId('studio-stunt-score')).toBeVisible()
 expect(errors).toEqual([])
})
test('private race invitation opens directly on a second browser with no codes to exchange',async({page},info)=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await lobby(page)
 await page.getByTestId('open-multiplayer').click()
 await expect(page.getByRole('dialog',{name:'Play with friends'})).toBeVisible()
 await page.getByTestId('studio-create-room').click()
 await expect(page.getByTestId('studio-room-link')).toHaveValue(/^https?:\/\/.+\/anik-block-racers\/\?view=battle#race=[0-9a-f]{32}$/,{timeout:30000})
 await expect(page.getByTestId('studio-offer-code')).toHaveCount(0)
 const link=await page.getByTestId('studio-room-link').inputValue()
 await page.screenshot({path:info.outputPath('studio-friend-invite.png'),animations:'disabled'})
 const local=new URL(link);local.protocol='http:';local.host='127.0.0.1:4173'
 const guest=await page.context().newPage(),guestErrors=[]
 guest.on('pageerror',e=>guestErrors.push(e.message))
 await guest.goto(local.href)
 await expect(guest.getByTestId('studio-room-lobby').or(guest.getByTestId('battle-multiplayer-status'))).toBeVisible({timeout:45000})
 await expect(guest.getByTestId('studio-offer-code')).toHaveCount(0)
 await guest.screenshot({path:info.outputPath('studio-friend-autojoin.png'),animations:'disabled'})
 await guest.close()
 expect(errors).toEqual([]);expect(guestErrors).toEqual([])
})
