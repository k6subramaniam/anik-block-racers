import {test,expect} from '@playwright/test'

async function ready(page,path='?view=battle'){
  await page.goto(`./${path}`)
  await expect(page.getByTestId('battle-start')).toBeEnabled({timeout:60_000})
  await expect(page.locator('canvas')).toHaveCount(1)
}
async function screenshot(page,info,name){await page.screenshot({path:info.outputPath(name+'.png'),animations:'disabled'})}

test('battle circuit mines hit the player and AI; bombs and mine buttons work',async({page},info)=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await ready(page)
  await screenshot(page,info,'battle-01-galaxy-lobby')
  await page.getByTestId('battle-start').click()
  await expect(page.getByTestId('battle-forward')).toBeVisible({timeout:15_000})
  await page.keyboard.down('w')
  await expect.poll(async()=>Number(await page.getByTestId('battle-armor').getAttribute('data-damage')),{timeout:15_000}).toBeGreaterThan(0)
  await screenshot(page,info,'battle-02-mine-hit')
  await page.keyboard.up('w')
  const health=Number(await page.getByTestId('battle-health').innerText());expect(health).toBeLessThan(100)
  await page.getByTestId('battle-bomb').click()
  await expect(page.getByTestId('battle-bomb')).toBeDisabled()
  await page.getByTestId('battle-mine').click()
  await expect(page.getByTestId('battle-mine')).toBeDisabled()
  const blastsBefore=Number(await page.getByTestId('battle-armor').getAttribute('data-blasts'))
  await expect.poll(async()=>Number(await page.getByTestId('battle-armor').getAttribute('data-blasts')),{timeout:12_000}).toBeGreaterThan(blastsBefore)
  await expect.poll(async()=>Math.min(...await page.locator('.br-rivals [data-hp]').evaluateAll(nodes=>nodes.map(n=>Number(n.dataset.hp)))),{timeout:18_000}).toBeLessThan(100)
  await screenshot(page,info,'battle-03-combat-hud')
  await page.getByTestId('battle-pause').click();await expect(page.getByTestId('battle-resume')).toBeVisible()
  const paused=await page.getByTestId('battle-time').innerText()
  const blasts=await page.getByTestId('battle-armor').getAttribute('data-blasts')
  await page.waitForTimeout(900)
  await expect(page.getByTestId('battle-time')).toHaveText(paused)
  await expect(page.getByTestId('battle-armor')).toHaveAttribute('data-blasts',blasts)
  await page.getByTestId('battle-resume').click()
  await page.getByTestId('battle-forward').dispatchEvent('pointerdown',{pointerId:5,pointerType:'touch'})
  await page.getByTestId('battle-left').dispatchEvent('pointerdown',{pointerId:6,pointerType:'touch'})
  await page.waitForTimeout(400)
  await page.getByTestId('battle-forward').dispatchEvent('pointercancel',{pointerId:5})
  await page.getByTestId('battle-left').dispatchEvent('pointercancel',{pointerId:6})
  await page.evaluate(()=>window.dispatchEvent(new Event('blur')))
  await expect(page.getByTestId('battle-resume')).toBeVisible()
  await page.getByRole('button',{name:'Back to home'}).click()
  await expect(page.getByTestId('home')).toBeVisible({timeout:30_000})
  expect(errors).toEqual([])
  console.log('BATTLE_COMBAT_VERIFIED',JSON.stringify({healthAfterMine:health,blastsAfterBomb:blasts,errors}))
})

test('all three race tracks render, have driving controls, and fit phone and desktop',async({page},info)=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await ready(page)
  for(const id of ['blast','canyon','frost']){
    await page.getByTestId(`battle-track-${id}`).click()
    await expect(page.getByTestId('battle-game')).toHaveAttribute('data-track',id)
    await screenshot(page,info,`battle-track-${id}`)
    await page.getByTestId('battle-start').click();await expect(page.getByTestId('battle-forward')).toBeVisible({timeout:15_000})
    await page.keyboard.down('w');await page.waitForTimeout(1100);await page.keyboard.up('w')
    await page.getByTestId('battle-pause').click();await page.getByRole('button',{name:'CHANGE TRACK',exact:true}).click()
  }
  for(const size of [{width:780,height:330},{width:360,height:740},{width:1280,height:720}]){
    await page.setViewportSize(size)
    await expect(page.getByTestId('battle-start')).toBeVisible()
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth)).toBe(true)
    const bounds=await page.getByTestId('battle-game').boundingBox()
    expect(bounds.width).toBe(size.width);expect(bounds.height).toBe(size.height)
    expect(bounds.x).toBe(0);expect(bounds.y).toBe(0)
    await screenshot(page,info,`battle-layout-${size.width}`)
  }
  expect(errors).toEqual([])
})

test('home screen opens every mode and challenge links still open Bot Smash',async({page},info)=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto('./?challenge=sd2-d20261028&score=250')
  await expect(page.getByTestId('sd-start')).toBeEnabled({timeout:60_000})
  await expect(page.getByTestId('sd-invite')).toContainText('250')
  await page.getByTestId('back-home').click()
  await expect(page.getByTestId('home')).toBeVisible()
  for(const id of ['grandprix','battle','smash','explore'])await expect(page.getByTestId(`home-${id}`)).toBeVisible()
  await page.getByTestId('home-battle').click()
  await expect(page.getByTestId('battle-start')).toBeEnabled({timeout:30_000})
  // The phone's back gesture returns home instead of leaving the game.
  await page.goBack()
  await expect(page.getByTestId('home')).toBeVisible()
  await page.getByTestId('home-smash').click()
  await expect(page.getByTestId('sd-invite')).toContainText('250')
  await page.getByTestId('back-home').click()
  await page.getByTestId('home-grandprix').click()
  await expect(page.getByTestId('start-explore')).toBeEnabled({timeout:60_000})
  await screenshot(page,info,'grand-prix-intro')
  await page.getByTestId('intro-home').click()
  await page.setViewportSize({width:360,height:740})
  await expect(page.getByTestId('home-battle')).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=document.documentElement.clientWidth)).toBeTruthy()
  await screenshot(page,info,'home-portrait')
  expect(errors).toEqual([])
})
