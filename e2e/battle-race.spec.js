import {test,expect} from '@playwright/test'
async function race(page){
 await page.goto('./?view=world')
 await expect(page.getByTestId('start-race')).toBeEnabled({timeout:60000})
 await expect(page.getByTestId('battle-toggle')).toHaveAttribute('aria-pressed','true')
 await page.getByTestId('start-race').click()
 await expect(page.getByTestId('throw-bomb')).toBeEnabled({timeout:15000})
}
test('battle race: bombs, mine damage, AI damage, protected controls and reset',async({page},info)=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await race(page)
 const hud=page.getByTestId('battle-hud')
 await expect(hud).toHaveAttribute('data-health','100')
 await page.screenshot({path:info.outputPath('battle-race-controls.png'),animations:'disabled'})
 await page.getByTestId('throw-bomb').click()
 await expect.poll(async()=>Number(await hud.getAttribute('data-shots'))).toBe(1)
 await page.waitForTimeout(3500)
 await page.getByTestId('drop-mine').click()
 await expect.poll(async()=>Number(await hud.getAttribute('data-shots'))).toBe(2)
 // Reverse into the player's own armed mine using actual keyboard driving.
 await page.waitForTimeout(1000)
 await page.keyboard.down('s');await page.waitForTimeout(1350);await page.keyboard.up('s')
 await expect.poll(async()=>Number(await hud.getAttribute('data-hits')),{timeout:15000}).toBeGreaterThan(0)
 await expect.poll(async()=>Number(await hud.getAttribute('data-bot-hits')),{timeout:35000}).toBeGreaterThan(0)
 await page.screenshot({path:info.outputPath('battle-player-and-ai-hit.png'),animations:'disabled'})
 const hp=Number(await hud.getAttribute('data-health'));expect(hp).toBeLessThan(100)
 await page.getByRole('button',{name:'Pause or resume race',exact:true}).click()
 await expect(page.getByTestId('throw-bomb')).toHaveCount(0)
 const clock=await page.getByTestId('race-time').innerText();await page.waitForTimeout(650)
 await expect(page.getByTestId('race-time')).toHaveText(clock)
 await page.keyboard.press('b')
 await page.getByRole('button',{name:'RESUME RACE',exact:true}).click()
 await expect.poll(async()=>Number(await hud.getAttribute('data-shots'))).toBe(2)
 await page.keyboard.press('r')
 await expect(page.getByTestId('throw-bomb')).toBeEnabled({timeout:15000})
 await expect(hud).toHaveAttribute('data-health','100');await expect(hud).toHaveAttribute('data-shots','0')
 await expect(page.getByTestId('throw-bomb')).toContainText('BOMB 3')
 expect(errors).toEqual([])
})
test('classic toggle, mobile hit targets and preserved exploration/Showdown',async({page},info)=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message))
 await page.goto('./?view=world');await expect(page.getByTestId('start-race')).toBeEnabled({timeout:60000})
 await page.getByTestId('battle-toggle').click()
 await expect(page.getByTestId('battle-toggle')).toHaveAttribute('aria-pressed','false')
 await page.getByTestId('start-race').click();await expect(page.getByTestId('touch-forward')).toBeVisible({timeout:15000})
 await expect(page.getByTestId('battle-hud')).toHaveCount(0)
 await page.getByTestId('open-settings').click();await page.getByTestId('battle-toggle').click()
 await page.getByText('BACK TO RACE',{exact:true}).click()
 await page.getByRole('button',{name:'RESUME RACE',exact:true}).click()
 await expect(page.getByTestId('throw-bomb')).toBeVisible()
 for(const viewport of [{width:915,height:412},{width:780,height:330},{width:412,height:915}]){
  await page.setViewportSize(viewport)
  await expect(page.getByTestId('throw-bomb')).toBeVisible()
  const bomb=await page.getByTestId('throw-bomb').boundingBox(),gas=await page.getByTestId('touch-forward').boundingBox()
  expect(bomb.y+bomb.height).toBeLessThanOrEqual(gas.y+2)
  expect(bomb.x).toBeGreaterThanOrEqual(0);expect(bomb.x+bomb.width).toBeLessThanOrEqual(viewport.width)
  await page.screenshot({path:info.outputPath(`battle-layout-${viewport.width}.png`),animations:'disabled'})
 }
 await page.getByTestId('switch-mode').click();await expect(page.getByTestId('battle-hud')).toHaveCount(0)
 await expect(page.getByTestId('touch-forward')).toBeVisible()
 await page.getByTestId('back-to-showdown').click();await expect(page.getByTestId('sd-start')).toBeEnabled({timeout:30000})
 expect(errors).toEqual([])
})
